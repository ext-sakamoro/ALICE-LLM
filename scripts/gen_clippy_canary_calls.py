#!/usr/bin/env python3
"""Generate scripts/clippy_canary_calls.tsv (the rows scripts/clippy_canary.py
plants) from clippy.toml.

One row per entry of `disallowed-methods` and `disallowed-types`, in clippy.toml
order. Other keys (`disallowed-macros`, ...) are not read. An entry is planted
when its first path segment is std, core, alloc or a primitive type, or names
an external crate locked in the repository's Cargo.lock (registry source; '-'
and '_' are equivalent). Every other entry becomes a skip row with the reason
it cannot be planted.

A method is planted as a bare path reference (`let _ = <path>;`), which clippy
flags once whatever the method's arity. A generic function cannot be named
without its type arguments (E0282), so the paths in GENERIC_PLANTS are planted
with the turbofish given there instead; clippy resolves the turbofish path to
the same disallowed method. A type is planted as a `use` item
(`#[allow(unused_imports)] use <path> as CanaryType;`), which clippy flags once
whatever the type's generic parameters.

`--check` compares the would-be output with the file byte for byte and exits 1
on drift. Either mode exits 1 when no row is plantable (compared nothing).

This script carries no repository-specific logic beyond the file names below.

usage: scripts/gen_clippy_canary_calls.py [--check] [--root DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import difflib
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clippy_canary as cc  # noqa: E402

ROOT = cc.ROOT
HEADER = """\
# Generated by scripts/gen_clippy_canary_calls.py from clippy.toml; do not edit.
# Regenerate: python3 scripts/gen_clippy_canary_calls.py
# Verify:     python3 scripts/gen_clippy_canary_calls.py --check
# One row per entry of disallowed-methods and disallowed-types, in clippy.toml
# order. Other keys (disallowed-macros and the like) are not read.
# Columns (tab separated):
#   planted: <clippy.toml key> <path> <Rust statement placed in a library function>
#   skipped: <clippy.toml key> <path> skip <reason it cannot be planted>
# scripts/clippy_canary.py plants every row that is not skipped.
"""


def own_crates(root: Path) -> set[str]:
    """Normalised names of the repository's own package and library."""
    names: set[str] = set()
    cargo = root / "Cargo.toml"
    if cargo.exists():
        data = tomllib.loads(cargo.read_text(encoding="utf-8"))
        for table in (data.get("package", {}), data.get("lib", {})):
            if isinstance(table.get("name"), str):
                names.add(cc.norm(table["name"]))
    return names


def skip_reason(path: str, lock: dict, own: set[str]) -> str | None:
    """None when the path can be planted, else why it cannot."""
    crate = cc.first_segment(path)
    if crate in cc.BUILTIN_ROOTS:
        return None
    if cc.norm(crate) in own:
        return f"{crate} is this repository's own crate: the canary crate does not build it"
    if cc.registry_version(lock, crate) is not None:
        return None
    if cc.norm(crate) in lock:
        return (f"{crate} is in Cargo.lock without a registry source: "
                "the canary crate cannot depend on it by version")
    return f"{crate} is not in Cargo.lock: the canary crate cannot depend on it"


# generic functions: a plant that compiles (type arguments given, lifetimes
# only where they are early-bound); each was checked to draw exactly one
# disallowed_methods diagnostic naming the path
GENERIC_PLANTS = {
    "std::thread::spawn": "let _ = std::thread::spawn::<fn(), ()>;",
    "std::thread::scope": "let _ = std::thread::scope::<'static, for<'s> fn(&'s std::thread::Scope<'s, 'static>), ()>;",
    "std::thread::Builder::spawn": "let _ = std::thread::Builder::spawn::<fn(), ()>;",
    "std::thread::Builder::spawn_scoped": "let _ = std::thread::Builder::spawn_scoped::<fn(), ()>;",
}


def statement(key: str, path: str) -> str:
    if key == "disallowed-methods":
        return GENERIC_PLANTS.get(path, f"let _ = {path};")
    return f"#[allow(unused_imports)] use {path} as CanaryType;"


def render(entries: dict[str, list[str]], lock: dict, own: set[str]) -> tuple[str, int, int]:
    """(file text, planted count, skipped count)"""
    lines: list[str] = []
    planted = skipped = 0
    for key in cc.KEYS:
        for path in entries.get(key, []):
            reason = skip_reason(path, lock, own)
            if reason is None:
                lines.append(f"{key}\t{path}\t{statement(key, path)}")
                planted += 1
            else:
                lines.append(f"{key}\t{path}\t{cc.SKIP}\t{reason}")
                skipped += 1
    return HEADER + "".join(f"{x}\n" for x in lines), planted, skipped


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file differs from the output")
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args(argv)
    out = args.out or args.root / "scripts" / "clippy_canary_calls.tsv"

    entries = cc.clippy_toml_entries((args.root / "clippy.toml").read_text(encoding="utf-8"))
    lock_file = args.root / "Cargo.lock"
    lock = cc.lock_packages(lock_file.read_text(encoding="utf-8")) if lock_file.exists() else {}
    text, planted, skipped = render(entries, lock, own_crates(args.root))
    if planted == 0:
        print(f"gen_clippy_canary_calls: compared nothing: no plantable entry among {skipped} "
              "disallowed-methods / disallowed-types entries of clippy.toml", file=sys.stderr)
        return 1
    summary = f"{planted} planted, {skipped} skipped"
    if args.check:
        current = out.read_bytes() if out.exists() else b""
        if current == text.encode("utf-8"):
            print(f"gen_clippy_canary_calls: {out.name} is up to date ({summary})")
            return 0
        diff = list(difflib.unified_diff(current.decode("utf-8", "replace").splitlines(),
                                         text.splitlines(), f"{out.name} (file)", f"{out.name} (generated)",
                                         lineterm="", n=0))
        changed = [d for d in diff if d[:1] in "+-" and not d.startswith(("+++", "---"))]
        print(f"gen_clippy_canary_calls: {out.name} is out of date: {len(changed)} line(s) differ; "
              "regenerate with python3 scripts/gen_clippy_canary_calls.py", file=sys.stderr)
        for d in changed[:40]:
            print(f"  {d}", file=sys.stderr)
        if len(changed) > 40:
            print(f"  ... {len(changed) - 40} more", file=sys.stderr)
        return 1
    out.write_bytes(text.encode("utf-8"))
    print(f"gen_clippy_canary_calls: wrote {out.name} ({summary})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
