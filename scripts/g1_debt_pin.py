#!/usr/bin/env python3
"""Pin every call of a G1-banned method (clippy.toml disallowed-methods) to a
tracked list, so that the scoped #[expect]s that keep CI green cannot hide a new
call.

The crate calls platform transcendentals in its inference code. Each enclosing
item carries `#[expect(clippy::disallowed_methods, reason = ...)]`, which keeps
`cargo clippy -D warnings` green and turns into an error once the item no longer
calls a banned method. An #[expect] covers a whole item, so it would also cover
a new call added to that item later, and any other lint-level attribute
(#[allow], an expect on a lint group, cfg_attr, an inner #![allow] in a module)
could silence one too. This script closes that gap without reading attributes:

1. run clippy with `--force-warn clippy::disallowed_methods`, which rustc
   applies over every lint-level attribute in the source (allow, expect,
   groups, cfg_attr, inner attributes), for every feature set the CI clippy
   job lints (read from .github/workflows/ci.yml, plus the default set) on both
   Linux targets (x86_64 and aarch64, so the arch-gated kernels of either are
   linted), once with `--lib --bins` (production code) and once with
   `--all-targets`;
2. compare the calls found with scripts/g1_debt_sites.tsv (production code, the
   recorded debt) and scripts/g1_reference_sites.tsv (tests, examples and
   #[cfg(test)] code), one `file<TAB>line<TAB>column<TAB>method` row each.

It fails on any difference (a new call, or a listed call that is gone: update
the list in the same commit as the fix), when no feature set was read from
ci.yml, and when no call was found at all (compared nothing).

Not covered: code compiled only for other operating systems
(cfg(target_os = "macos" / "windows")), since both targets are Linux.

usage: scripts/g1_debt_pin.py [--write]
"""
from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEBT = ROOT / "scripts" / "g1_debt_sites.tsv"
REFERENCE = ROOT / "scripts" / "g1_reference_sites.tsv"
WORKFLOW = ROOT / ".github" / "workflows" / "ci.yml"
LINT = "clippy::disallowed_methods"
TARGETS = ("x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu")
HEADER = ("# Generated by scripts/g1_debt_pin.py --write; do not edit by hand.\n"
          "# Every call of a G1-banned method (clippy.toml) in {what}.\n"
          "# Columns (tab separated): file, line, column, method\n")


def feature_sets(workflow: str) -> list[list[str]]:
    """The --features arguments of every `cargo clippy` command in ci.yml,
    plus the default set, as cargo argument lists."""
    sets: list[list[str]] = [[]]
    for line in workflow.splitlines():
        if "cargo clippy" not in line:
            continue
        cmd = line.split("run:", 1)[-1].strip()
        args = shlex.split(cmd.split(" -- ")[0])
        for i, a in enumerate(args):
            if a == "--features" and i + 1 < len(args):
                fs = ["--features", args[i + 1]]
                if fs not in sets:
                    sets.append(fs)
    return sets


def clippy_command(target: str, features: list[str], scope: list[str]) -> list[str]:
    """--force-warn makes rustc report the lint whatever the source says."""
    return ["cargo", "clippy", *scope, "--target", target, *features,
            "--message-format=json", "--", "--force-warn", LINT]


def parse_sites(lines) -> set[tuple[str, int, int, str]]:
    sites = set()
    for raw in lines:
        try:
            msg = json.loads(raw)
        except json.JSONDecodeError:
            continue
        if msg.get("reason") != "compiler-message":
            continue
        diag = msg["message"]
        if (diag.get("code") or {}).get("code") != LINT:
            continue
        span = next(s for s in diag["spans"] if s.get("is_primary"))
        method = diag["message"].split("`")[1]
        sites.add((span["file_name"], span["line_start"], span["column_start"], method))
    return sites


def read_list(path: Path) -> set[tuple[str, int, int, str]]:
    rows = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        f, ln, col, meth = line.split("\t")
        rows.add((f, int(ln), int(col), meth))
    return rows


def write_list(path: Path, rows, what: str) -> None:
    body = "".join(f"{f}\t{ln}\t{col}\t{m}\n" for f, ln, col, m in sorted(rows))
    path.write_text(HEADER.format(what=what) + body, encoding="utf-8")


def clippy(target: str, features: list[str], scope: list[str]) -> set:
    env = dict(os.environ)
    env["RUSTFLAGS"] = ""  # warnings must not stop the build: every target has to be linted
    env["CARGO_TARGET_DIR"] = str(ROOT / "target" / "g1-pin")
    cmd = clippy_command(target, features, scope)
    proc = subprocess.run(cmd, cwd=ROOT, env=env, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, text=True, encoding="utf-8", check=False)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr[-4000:])
        raise SystemExit(f"g1_debt_pin: `{' '.join(cmd)}` failed (rc {proc.returncode})")
    return parse_sites(proc.stdout.splitlines())


def main(argv: list[str]) -> int:
    sets = feature_sets(WORKFLOW.read_text(encoding="utf-8"))
    if len(sets) < 2:
        print("g1_debt_pin: no --features set read from ci.yml (compared nothing)", file=sys.stderr)
        return 1
    production, everything = set(), set()
    for target in TARGETS:
        for fs in sets:
            production |= clippy(target, fs, ["--lib", "--bins"])
            everything |= clippy(target, fs, ["--all-targets"])
    reference = everything - production
    if not everything:
        print("g1_debt_pin: clippy reported no banned call (compared nothing)", file=sys.stderr)
        return 1
    if "--write" in argv:
        write_list(DEBT, production, "production code (lib and bins): recorded G1 debt")
        write_list(REFERENCE, reference, "tests, examples and #[cfg(test)] code")
        print(f"g1_debt_pin: wrote {len(production)} debt and {len(reference)} reference sites")
        return 0
    bad = 0
    for path, found in ((DEBT, production), (REFERENCE, reference)):
        listed = read_list(path)
        for row in sorted(found - listed):
            print(f"g1_debt_pin: not listed in {path.name}: {row[0]}:{row[1]}:{row[2]} {row[3]}", file=sys.stderr)
            bad += 1
        for row in sorted(listed - found):
            print(f"g1_debt_pin: listed in {path.name} but not called: {row[0]}:{row[1]}:{row[2]} {row[3]}", file=sys.stderr)
            bad += 1
    if bad:
        return 1
    print(f"g1_debt_pin: {len(production)} debt + {len(reference)} reference sites match the lists "
          f"(--force-warn {LINT}, {len(sets)} feature sets x {len(TARGETS)} targets)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
