#!/usr/bin/env python3
"""Tests for scripts/gen_clippy_canary_calls.py: the row forms, plantable versus
skipped entries, clippy.toml order, the keys that are not read, `--check` drift
detection, the compared-nothing failure, and that the generated file parses
back to rows equal to the clippy.toml entries."""
import contextlib
import io
import os
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import clippy_canary as cc  # noqa: E402
import gen_clippy_canary_calls as gen  # noqa: E402

TOML = """
disallowed-macros = [{ path = "std::println", reason = "not read" }]
disallowed-methods = [
    { path = "f64::sin", reason = "r" },
    "u128::pow",
    { path = "std::time::Instant::now", reason = "r" },
    { path = "dep_a::clock::now", reason = "r" },
    { path = "my_crate::inner::f", reason = "r" },
    { path = "local_dep::f", reason = "r" },
    { path = "nowhere::f", reason = "r" },
]
disallowed-types = [
    { path = "std::collections::HashMap", reason = "r" },
    { path = "nowhere::T", reason = "r" },
]
"""
CARGO = '[package]\nname = "my-crate"\nversion = "0.1.0"\nedition = "2021"\n'
LOCK = """version = 4

[[package]]
name = "my-crate"
version = "0.1.0"

[[package]]
name = "dep-a"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "local-dep"
version = "0.3.0"
"""


def repo(d, toml=TOML, lock=LOCK):
    root = Path(d)
    (root / "scripts").mkdir()
    (root / "clippy.toml").write_text(toml, encoding="utf-8")
    (root / "Cargo.toml").write_text(CARGO, encoding="utf-8")
    if lock is not None:
        (root / "Cargo.lock").write_text(lock, encoding="utf-8")
    return root


def run(args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        rc = gen.main(args)
    return rc, out.getvalue(), err.getvalue()


def body(text):
    return [line for line in text.splitlines() if line and not line.startswith("#")]


class Render(unittest.TestCase):
    def setUp(self):
        self.text, self.planted, self.skipped = gen.render(
            cc.clippy_toml_entries(TOML), cc.lock_packages(LOCK), {"my_crate"})
        self.rows = body(self.text)

    def test_header_comes_first(self):
        self.assertTrue(self.text.startswith(gen.HEADER))
        self.assertIn("Generated by scripts/gen_clippy_canary_calls.py", gen.HEADER)
        self.assertIn("python3 scripts/gen_clippy_canary_calls.py", gen.HEADER)
        self.assertIn("disallowed-macros", gen.HEADER)
        self.assertIn("Columns (tab separated)", gen.HEADER)

    def test_one_row_per_entry_in_clippy_toml_order(self):
        self.assertEqual([r.split("\t")[1] for r in self.rows],
                         ["f64::sin", "u128::pow", "std::time::Instant::now", "dep_a::clock::now",
                          "my_crate::inner::f", "local_dep::f", "nowhere::f",
                          "std::collections::HashMap", "nowhere::T"])
        self.assertEqual((self.planted, self.skipped), (5, 4))

    def test_macros_are_not_read(self):
        self.assertNotIn("println", "\n".join(self.rows))

    def test_method_and_type_row_forms(self):
        self.assertIn("disallowed-methods\tf64::sin\tlet _ = f64::sin;", self.rows)
        self.assertIn("disallowed-methods\tu128::pow\tlet _ = u128::pow;", self.rows)
        self.assertIn("disallowed-methods\tdep_a::clock::now\tlet _ = dep_a::clock::now;", self.rows)
        self.assertIn("disallowed-types\tstd::collections::HashMap\t"
                      "#[allow(unused_imports)] use std::collections::HashMap as CanaryType;", self.rows)

    def test_generic_functions_are_planted_with_their_turbofish(self):
        for path, plant in gen.GENERIC_PLANTS.items():
            self.assertEqual(gen.statement("disallowed-methods", path), plant, path)
            self.assertTrue(plant.startswith(f"let _ = {path}::<") and plant.endswith(">;"), plant)
        self.assertEqual(set(gen.GENERIC_PLANTS), {"std::thread::spawn", "std::thread::scope",
                                                   "std::thread::Builder::spawn",
                                                   "std::thread::Builder::spawn_scoped"})
        # a non-generic method keeps the bare path form
        self.assertEqual(gen.statement("disallowed-methods", "f64::sin"), "let _ = f64::sin;")

    def test_methods_of_generic_types_are_named_through_the_type(self):
        for owner, named in gen.GENERIC_TYPES.items():
            self.assertTrue(named.startswith(f"{owner}::<") and named.endswith(">"), named)
            self.assertEqual(gen.statement("disallowed-methods", f"{owner}::norm"),
                             f"let _ = {named}::norm;")
        # a path that only shares a prefix with a generic type keeps the bare form
        self.assertEqual(gen.statement("disallowed-methods", "num_complex::ComplexFloat::abs"),
                         "let _ = num_complex::ComplexFloat::abs;")

    def test_skip_rows_name_the_reason(self):
        skips = {r.split("\t")[1]: r.split("\t")[3] for r in self.rows if r.split("\t")[2] == "skip"}
        self.assertEqual(set(skips), {"my_crate::inner::f", "local_dep::f", "nowhere::f", "nowhere::T"})
        self.assertIn("my_crate is this repository's own crate", skips["my_crate::inner::f"])
        self.assertIn("without a registry source", skips["local_dep::f"])
        self.assertEqual(skips["nowhere::f"], "nowhere is not in Cargo.lock: the canary crate cannot depend on it")
        self.assertTrue(all(skips.values()))

    def test_a_git_source_is_plantable(self):
        lock = LOCK + ('\n[[package]]\nname = "dep-g"\nversion = "0.6.0"\n'
                       f'source = "git+https://example.invalid/dep-g?rev=aaaaaaa#{"a" * 40}"\n')
        self.assertIsNone(gen.skip_reason("dep_g::Key::generate", cc.lock_packages(lock), set()))

    def test_a_declared_path_source_is_plantable_and_an_undeclared_one_is_not(self):
        lock = cc.lock_packages(LOCK)
        self.assertIsNone(gen.skip_reason("local_dep::f", lock, set(), {"local_dep": "/r/local-dep"}))
        self.assertIn("without a registry source", gen.skip_reason("local_dep::f", lock, set(), {}))

    def test_hyphen_and_underscore_are_equivalent(self):
        self.assertIsNone(gen.skip_reason("dep_a::x", cc.lock_packages(LOCK), set()))
        self.assertIsNone(gen.skip_reason("dep-a::x", cc.lock_packages(LOCK), set()))

    def test_every_builtin_root_is_plantable(self):
        for root in ("std", "core", "alloc", "f32", "f64", "i8", "i128", "u8", "u128", "isize", "usize",
                     "bool", "char", "str"):
            self.assertIsNone(gen.skip_reason(f"{root}::x", {}, set()), root)

    def test_the_output_parses_back_equal_to_clippy_toml(self):
        rows, problems = cc.parse_rows(self.text)
        self.assertEqual(problems, [])
        self.assertEqual(cc.equality(rows, cc.clippy_toml_entries(TOML)), [])
        self.assertEqual(cc.dependencies(rows, cc.lock_packages(LOCK))[1], [])


class Main(unittest.TestCase):
    def test_a_path_dependency_the_root_manifest_declares_is_planted(self):
        with tempfile.TemporaryDirectory() as d:
            root = repo(d)
            (root / "Cargo.toml").write_text(CARGO + '\n[dependencies]\nlocal-dep = { path = "../local-dep" }\n',
                                             encoding="utf-8")
            rc, _, err = run(["--root", str(root)])
            self.assertEqual(rc, 0, err)
            text = (root / "scripts" / "clippy_canary_calls.tsv").read_text(encoding="utf-8")
        row = [line for line in body(text) if "\tlocal_dep::f\t" in line]
        self.assertEqual(len(row), 1, text)
        self.assertNotIn("\tskip\t", row[0])

    def test_write_then_check_passes(self):
        with tempfile.TemporaryDirectory() as d:
            root = repo(d)
            self.assertEqual(run(["--root", str(root)])[0], 0)
            rc, out, _ = run(["--root", str(root), "--check"])
        self.assertEqual(rc, 0)
        self.assertIn("up to date (5 planted, 4 skipped)", out)

    def test_check_fails_on_a_deleted_row(self):
        with tempfile.TemporaryDirectory() as d:
            root = repo(d)
            run(["--root", str(root)])
            f = root / "scripts" / "clippy_canary_calls.tsv"
            f.write_text("".join(l for l in f.read_text(encoding="utf-8").splitlines(True)
                                 if "f64::sin" not in l), encoding="utf-8")
            rc, _, err = run(["--root", str(root), "--check"])
        self.assertEqual(rc, 1)
        self.assertIn("out of date: 1 line(s) differ", err)
        self.assertIn("+disallowed-methods\tf64::sin", err)

    def test_check_fails_on_a_new_clippy_toml_entry(self):
        with tempfile.TemporaryDirectory() as d:
            root = repo(d)
            run(["--root", str(root)])
            (root / "clippy.toml").write_text(TOML.replace('"u128::pow",', '"u128::pow", "f32::cos",'),
                                              encoding="utf-8")
            rc, _, err = run(["--root", str(root), "--check"])
        self.assertEqual(rc, 1)
        self.assertIn("f32::cos", err)

    def test_check_compares_bytes(self):
        with tempfile.TemporaryDirectory() as d:
            root = repo(d)
            run(["--root", str(root)])
            f = root / "scripts" / "clippy_canary_calls.tsv"
            f.write_bytes(f.read_bytes().replace(b"\n", b"\r\n"))
            self.assertEqual(run(["--root", str(root), "--check"])[0], 1)

    def test_check_fails_when_the_file_is_missing(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertEqual(run(["--root", str(repo(d)), "--check"])[0], 1)

    def test_nothing_plantable_compares_nothing(self):
        toml = 'disallowed-methods = [{ path = "nowhere::f", reason = "r" }]\n'
        for args in ([], ["--check"]):
            with tempfile.TemporaryDirectory() as d:
                rc, _, err = run(["--root", str(repo(d, toml=toml, lock=None)), *args])
            self.assertEqual(rc, 1)
            self.assertIn("compared nothing", err)

    def test_no_entries_compares_nothing(self):
        with tempfile.TemporaryDirectory() as d:
            rc, _, err = run(["--root", str(repo(d, toml="disallowed-macros = []\n"))])
        self.assertEqual(rc, 1)
        self.assertIn("compared nothing", err)

    def test_the_repository_file_is_up_to_date(self):
        rc, _, err = run(["--check"])
        self.assertEqual(rc, 0, err)


if __name__ == "__main__":
    unittest.main()
